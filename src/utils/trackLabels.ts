const spanishBases: Record<string, string> = {
  Audio: 'Audio',
  Subtitles: 'Subtítulos',
  Unknown: 'Desconocido',
};

const isSpanish = (locale: string) => String(locale || '').toLowerCase().startsWith('es');

/** A language name ("German") in the locale ("Alemán"). */
export function localizeLanguageName(name: string, locale: string): string {
  const trimmed = String(name || '').trim();
  if (!isSpanish(locale)) return trimmed;
  return spanishLanguages[trimmed] || spanishBases[trimmed] || trimmed;
}

const labelPattern = /^(.*?)(?: \(([^()]*)\))?(?: (\d+))?$/;

/** A track label ("French (Canada, Forced)") in the locale ("Francés (Canadá, Forzados)"). */
export function localizeTrackLabel(label: string, locale: string): string {
  const trimmed = String(label || '').trim();
  if (!isSpanish(locale) || !trimmed) return trimmed;
  const match = labelPattern.exec(trimmed);
  if (!match) return trimmed;
  const [, base, details, number] = match;
  let out = localizeLanguageName(base, locale);
  if (details) out += ` (${details.split(', ').map((detail) => spanishDetails[detail] || detail).join(', ')})`;
  if (number) out += ` ${number}`;
  return out;
}
